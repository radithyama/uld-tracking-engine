#!/usr/bin/env bash
# GCE startup script for the ULD Tracking Engine demo.
#
# Compute Engine runs this as root on EVERY boot, so each step is idempotent.
# It bootstraps the host (swap, Docker, Node, git checkout, config generated
# from instance metadata) and then runs deploy/gcp/deploy.sh, the same script
# GitHub Actions runs on every push to main. Follow progress with:
#   sudo journalctl -u google-startup-scripts.service -f
set -euo pipefail
exec > >(tee -a /var/log/uld-startup.log) 2>&1
echo "=== uld startup $(date -Is) ==="

REPO_URL=https://github.com/radithyama/uld-tracking-engine.git
APP_DIR=/opt/uld-tracking-engine
export DEBIAN_FRONTEND=noninteractive

md() { curl -fsS -H 'Metadata-Flavor: Google' "http://metadata.google.internal/computeMetadata/v1/$1"; }
PUBLIC_IP=$(md instance/network-interfaces/0/access-configs/0/external-ip)
SIM_RATE=$(md instance/attributes/uld-sim-rate 2>/dev/null || echo 5)
# Optional: set when the site is served over HTTPS behind Nginx, e.g.
#   gcloud compute instances add-metadata uld-demo --metadata=uld-domain=example.com
DOMAIN=$(md instance/attributes/uld-domain 2>/dev/null || true)
if [ -n "$DOMAIN" ]; then
  ORIGINS="https://${DOMAIN},https://www.${DOMAIN}"
  WS_URL="wss://${DOMAIN}/ws"
else
  ORIGINS="http://${PUBLIC_IP}:3000"
  WS_URL="ws://${PUBLIC_IP}:8081/ws"
fi
echo "public ip: $PUBLIC_IP, domain: ${DOMAIN:-none}, ws: $WS_URL, simulator rate: $SIM_RATE/s"

# --- 0. Swap: e2-micro has 1 GB RAM; image builds and Kafka need headroom ---
if ! swapon --show | grep -q /swapfile; then
  [ -f /swapfile ] || { fallocate -l 4G /swapfile; chmod 600 /swapfile; mkswap /swapfile; }
  swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  echo 'vm.swappiness=30' > /etc/sysctl.d/99-uld.conf && sysctl -p /etc/sysctl.d/99-uld.conf
fi

# --- 1-3. apt index, Docker Engine + Compose plugin (official repo), Git ---
if ! command -v docker >/dev/null; then
  apt-get update
  apt-get install -y ca-certificates curl git
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] \
https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "${UBUNTU_CODENAME:-$VERSION_CODENAME}") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
fi
command -v git >/dev/null || apt-get install -y git

# --- 6a. Node.js 22 LTS (Next.js 16 needs >= 20.9; Ubuntu's apt ships 18) ---
if ! command -v node >/dev/null; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi

# --- 4. Clone (first boot) or fast-forward (later boots) ---
if [ -d "$APP_DIR/.git" ]; then
  git -C "$APP_DIR" pull --ff-only || echo "git pull failed; keeping current checkout"
else
  git clone --depth 1 "$REPO_URL" "$APP_DIR"
fi
cd "$APP_DIR"

# Dashboard origin(s) allowed by the realtime WebSocket (read by compose from .env).
echo "ALLOWED_ORIGINS=${ORIGINS}" > .env

# Low-memory tuning for e2-micro; compose merges this over docker-compose.yml.
cat > docker-compose.override.yml <<EOF
# Generated by deploy/gcp/startup.sh. Low-memory tuning for small VMs.
services:
  kafka:
    environment:
      KAFKA_HEAP_OPTS: "-Xms128m -Xmx256m"   # default is a 1 GB heap
    healthcheck:
      interval: 30s        # each probe starts a JVM; keep them rare
      timeout: 25s
      start_period: 180s
  postgres:
    command: ["postgres", "-c", "shared_buffers=32MB", "-c", "max_connections=30"]
  processor:
    environment:
      PROCESSOR_WORKERS: "2"
  simulator:
    environment:
      SIM_RATE: "${SIM_RATE}"
EOF

# --- 5 + 6b. Build and start backend + dashboard (shared with CI deploys) ---
WS_URL="$WS_URL" bash "$APP_DIR/deploy/gcp/deploy.sh"

if [ -n "$DOMAIN" ]; then
  echo "=== done: dashboard https://${DOMAIN}  ingest https://${DOMAIN}/api/healthz ==="
else
  echo "=== done: dashboard http://${PUBLIC_IP}:3000  ingest http://${PUBLIC_IP}:8080 ==="
fi
